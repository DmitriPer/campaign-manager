#!/usr/bin/env node
// Generates src/app/core/supabase.config.generated.ts (git-ignored) from
// SUPABASE_URL and SUPABASE_PUBLISHABLE_KEY. Environment variables win; otherwise
// values are read from .env.local. Fails loudly when either value is missing so a
// misconfigured build never ships placeholders.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const envFile = join(root, '.env.local');
const outFile = join(root, 'src/app/core/supabase.config.generated.ts');

function readEnvFile(path) {
  if (!existsSync(path)) return {};
  const values = {};
  for (const line of readFileSync(path, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m) values[m[1]] = m[2].replace(/^(['"])(.*)\1$/, '$2');
  }
  return values;
}

const fileValues = readEnvFile(envFile);
const pick = (name) => process.env[name] || fileValues[name] || '';

const url = pick('SUPABASE_URL');
const publishableKey = pick('SUPABASE_PUBLISHABLE_KEY');

const problems = [];
if (!/^https?:\/\/[^\s/]+/.test(url)) problems.push('SUPABASE_URL is missing or not a URL');
if (!publishableKey) problems.push('SUPABASE_PUBLISHABLE_KEY is missing');
if (/^sb_secret_/.test(publishableKey) || /service_role/.test(publishableKey)) {
  problems.push('SUPABASE_PUBLISHABLE_KEY looks like a secret key; never use it in the browser');
}
if (problems.length) {
  console.error('Supabase config error:\n  - ' + problems.join('\n  - '));
  console.error('Copy .env.example to .env.local and fill it in, or set the variables in the environment.');
  process.exit(1);
}

const content =
  '// GENERATED by scripts/write-supabase-config.mjs. Do not edit or commit.\n' +
  `export const supabaseConfig = ${JSON.stringify(
    { url: url.replace(/\/+$/, ''), publishableKey },
    null,
    2,
  )} as const;\n`;
writeFileSync(outFile, content);
console.log(`Supabase config written for ${new URL(url).host}`);
